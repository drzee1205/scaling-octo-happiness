export default function Builder() {
  const [input, setInput] = useState("build login page with Tailwind and JWT auth, add dashboard with task list");
  const history = useHistory<Project>(buildProject(input));

  // live preview update when input changes
  useEffect(() => {
    const id = setTimeout(() => {
      history.set(buildProject(input));
    }, 400);
    return () => clearTimeout(id);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [input]);

  useEffect(() => {
    // restore from URL if present
    const hash = location.hash.replace(/^#/, "");
    if (hash) {
      try {
        const json = decompressFromEncodedURIComponent(hash);
        if (json) {
          const proj = JSON.parse(json) as Project;
          setInput(proj.command);
          history.set(proj);
        }
      } catch {}
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  const share = () => {
    const encoded = compressToEncodedURIComponent(JSON.stringify(history.state));
    const url = `${location.origin}/builder#${encoded}`;
    navigator.clipboard.writeText(url);
    toast("Share link copied to clipboard");
  };

  const files = useMemo(() => asSandpackFiles(history.state.frontend), [history.state.frontend]);

  return (
    <div className="mx-auto max-w-[1200px] px-4 py-8">
      <Toaster />
      <h1 className="text-3xl font-bold gradient-text">Loveable Builder</h1>
      <p className="text-muted-foreground mt-1">Type a command. We'll interpret it, generate code, and live-preview the UI. Backend/API and Prisma schema are generated too.</p>

      <Card className="mt-6 p-4">
        <div className="flex flex-col gap-3 md:flex-row md:items-center">
          <Textarea value={input} onChange={(e)=>setInput(e.target.value)} className="min-h-20" placeholder="e.g. build login page with Tailwind and JWT auth" />
          <div className="flex gap-2 md:self-start">
            <Button onClick={()=>history.set(buildProject(input))}><Play className="mr-2 h-4 w-4"/>Build</Button>
            <Button variant="outline" onClick={history.undo} disabled={!history.canUndo}><Undo2 className="mr-2 h-4 w-4"/>Undo</Button>
            <Button variant="outline" onClick={history.redo} disabled={!history.canRedo}><Redo2 className="mr-2 h-4 w-4"/>Redo</Button>
            <Button variant="outline" onClick={share}><Share2 className="mr-2 h-4 w-4"/>Share</Button>
            <Button variant="outline" onClick={()=>downloadZip(history.state)}><Download className="mr-2 h-4 w-4"/>Download</Button>
          </div>
        </div>
        <div className="mt-2 flex flex-wrap items-center gap-2">
          <Badge variant="secondary">Auth: {history.state.ir.auth.type.toUpperCase()}</Badge>
          <Badge variant="secondary">Pages: {history.state.ir.pages.length}</Badge>
          <Badge variant="secondary">Models: {history.state.ir.models.length}</Badge>
        </div>
      </Card>

      <Tabs defaultValue="preview" className="mt-6">
        <TabsList>
          <TabsTrigger value="preview">Preview</TabsTrigger>
          <TabsTrigger value="frontend">Frontend Files</TabsTrigger>
          <TabsTrigger value="api">API Routes</TabsTrigger>
          <TabsTrigger value="prisma">Prisma Schema</TabsTrigger>
          <TabsTrigger value="ir">IR</TabsTrigger>
        </TabsList>
        <TabsContent value="preview" className="mt-4">
          <SandpackProvider files={files} template="vite-react-ts" options={{ recompileMode: "immediate" }}>
            <SandpackLayout>
              <SandpackPreview className="rounded-lg border" />
              <SandpackCodeEditor showTabs wrapContent style={{ height: 400 }} />
            </SandpackLayout>
          </SandpackProvider>
        </TabsContent>
        <TabsContent value="frontend" className="mt-4">
          <CodeList files={history.state.frontend} />
        </TabsContent>
        <TabsContent value="api" className="mt-4">
          <CodeList files={history.state.backend} />
        </TabsContent>
        <TabsContent value="prisma" className="mt-4">
          <pre className="rounded-lg border bg-black/50 p-4 text-xs text-white/90 overflow-auto"><code>{history.state.prisma}</code></pre>
        </TabsContent>
        <TabsContent value="ir" className="mt-4">
          <pre className="rounded-lg border bg-black/50 p-4 text-xs text-white/90 overflow-auto"><code>{JSON.stringify(history.state.ir, null, 2)}</code></pre>
        </TabsContent>
      </Tabs>

      <div className="mt-8 text-sm text-muted-foreground">
        <p>Notes/assumptions:</p>
        <ul className="list-disc pl-5">
          {history.state.ir.notes?.map((n)=> <li key={n}>{n}</li>)}
        </ul>
      </div>
    </div>
  );
}

function CodeList({ files }: { files: Record<string, string> }){
  return (
    <div className="grid grid-cols-1 gap-4 md:grid-cols-2">
      {Object.entries(files).map(([path, code]) => (
        <Card key={path} className="overflow-hidden">
          <div className="flex items-center justify-between border-b px-4 py-2 text-xs">
            <span className="text-muted-foreground">{path}</span>
            <Button variant="ghost" size="sm" onClick={()=>{navigator.clipboard.writeText(code)}}><Copy className="h-4 w-4"/></Button>
          </div>
          <pre className="max-h-80 overflow-auto bg-black/50 p-4 text-xs text-white/90"><code>{code}</code></pre>
        </Card>
      ))}
    </div>
  );
}