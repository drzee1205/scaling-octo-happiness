// ---------------- Types ----------------
export type IR = {
  pages: Array<{ name: string; path: string; type: "landing" | "login" | "dashboard" | "custom"; widgets?: string[] }>;
  models: Array<{ name: string; fields: Array<{ name: string; type: string; optional?: boolean }> }>;
  auth: { type: "jwt" | "oauth"; providers?: string[] };
  apis: Array<{ method: "GET" | "POST" | "PUT" | "DELETE"; route: string; model?: string; action?: string }>;
  notes?: string[]; // assumptions
};

export type Project = {
  command: string;
  ir: IR;
  frontend: Record<string, string>; // file path -> contents
  backend: Record<string, string>; // nextjs app router files
  prisma: string;
};

// ---------------- Parser ----------------
function parseCommand(command: string): IR {
  const lower = command.toLowerCase();
  const pages: IR["pages"] = [];
  if (/(landing|home|marketing)/.test(lower)) pages.push({ name: "Home", path: "/", type: "landing" });
  if (/login|auth/.test(lower)) pages.push({ name: "Login", path: "/login", type: "login" });
  if (/dashboard/.test(lower)) pages.push({ name: "Dashboard", path: "/dashboard", type: "dashboard" });
  if (pages.length === 0) pages.push({ name: "Home", path: "/", type: "custom", widgets: ["hero", "cta"] });

  const models: IR["models"] = [];
  if (/user/.test(lower) || /auth/.test(lower)) {
    models.push({
      name: "User",
      fields: [
        { name: "id", type: "String" },
        { name: "email", type: "String" },
        { name: "passwordHash", type: "String" },
        { name: "createdAt", type: "DateTime" },
      ],
    });
  }
  if (/todo|task/.test(lower)) {
    models.push({
      name: "Task",
      fields: [
        { name: "id", type: "String" },
        { name: "title", type: "String" },
        { name: "completed", type: "Boolean" },
        { name: "userId", type: "String" },
      ],
    });
  }

  const auth: IR["auth"] = /oauth/.test(lower)
    ? { type: "oauth", providers: ["github"] }
    : { type: "jwt" };

  const apis: IR["apis"] = [];
  // Basic CRUD APIs for detected models
  for (const m of models) {
    apis.push({ method: "GET", route: `/api/${m.name.toLowerCase()}s`, model: m.name, action: "list" });
    apis.push({ method: "POST", route: `/api/${m.name.toLowerCase()}s`, model: m.name, action: "create" });
  }
  if (auth.type === "jwt") {
    apis.push({ method: "POST", route: "/api/auth/login", action: "login" });
    apis.push({ method: "POST", route: "/api/auth/register", action: "register" });
  }

  const notes: string[] = [];
  if (!/db|prisma|postgres/.test(lower)) notes.push("Assumption: Using Prisma + Postgres for persistence.");
  if (!/auth/.test(lower)) notes.push("Assumption: JWT auth by default.");

  return { pages, models, auth, apis, notes };
}

// ---------------- Generators ----------------
function genPrisma(ir: IR) {
  const base = `// Prisma schema generated by Loveable\n// Assumption: Using PostgreSQL\n// Set DATABASE_URL in .env before running\n\n datasource db {\n  provider = "postgresql"\n  url      = env("DATABASE_URL")\n }\n\n generator client {\n  provider = "prisma-client-js"\n }\n`;

  const models = ir.models.length
    ? ir.models
        .map((m) => {
          const fields = m.fields
            .map((f) => {
              const type = f.type === "DateTime" ? "DateTime" : f.type;
              const id = f.name === "id" ? " @id @default(cuid())" : "";
              return `  ${f.name} ${type}${f.optional ? "?" : ""}${id}`;
            })
            .join("\n");
          return `\nmodel ${m.name} {\n${fields}\n}`;
        })
        .join("\n")
    : `\nmodel User {\n  id          String   @id @default(cuid())\n  email       String   @unique\n  passwordHash String\n  createdAt   DateTime @default(now())\n}`;

  return base + models + "\n";
}

