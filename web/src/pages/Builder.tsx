function genNextApiFiles(ir: IR): Record<string, string> {
  const files: Record<string, string> = {};
  // Basic app router structure
  files["/app/page.tsx"] = `export default function Home(){ return <main>Loveable App</main> }`;
  files["/package.json"] = `{
  "name": "loveable-app",
  "private": true,
  "scripts": { "dev": "next dev", "build": "next build", "start": "next start" },
  "dependencies": { "next": "14.2.10", "react": "19.0.0", "react-dom": "19.0.0", "prisma": "^5.16.1", "@prisma/client": "^5.16.1", "jsonwebtoken": "^9.0.2", "bcryptjs": "^2.4.3" }
}`;
  files["/tsconfig.json"] = `{
  "compilerOptions": { "strict": true, "jsx": "preserve", "module": "esnext", "target": "es2022", "moduleResolution": "bundler", "baseUrl": "." },
  "include": ["next-env.d.ts", "**/*.ts", "**/*.tsx"],
  "exclude": ["node_modules"]
}`;
  files["/next.config.js"] = `/** @type {import('next').NextConfig} */\nmodule.exports = { experimental: { serverActions: true } }`;
  files["/.env.example"] = `# Required: set the Postgres connection URL\nDATABASE_URL=postgresql://user:pass@host:5432/db\n# JWT secret for signing tokens\nJWT_SECRET=change-me`;
  files["/prisma/schema.prisma"] = genPrisma(ir);

  // Auth routes
  files["/app/api/auth/login/route.ts"] = `import { NextRequest, NextResponse } from 'next/server'\nimport jwt from 'jsonwebtoken'\nimport bcrypt from 'bcryptjs'\nimport { PrismaClient } from '@prisma/client'\nconst prisma = new PrismaClient()\nexport async function POST(req: NextRequest){\n  const { email, password } = await req.json()\n  // In production add rate-limit and validation\n  const user = await prisma.user.findUnique({ where: { email } })\n  if(!user || !bcrypt.compareSync(password, user.passwordHash)) return NextResponse.json({ error: 'Invalid credentials' }, { status: 401 })\n  const token = jwt.sign({ sub: user.id, email }, process.env.JWT_SECRET!, { expiresIn: '1d' })\n  return NextResponse.json({ token })\n}`;

  files["/app/api/auth/register/route.ts"] = `import { NextRequest, NextResponse } from 'next/server'\nimport bcrypt from 'bcryptjs'\nimport { PrismaClient } from '@prisma/client'\nconst prisma = new PrismaClient()\nexport async function POST(req: NextRequest){\n  const { email, password } = await req.json()\n  const existing = await prisma.user.findUnique({ where: { email } })\n  if(existing) return NextResponse.json({ error: 'Email taken' }, { status: 409 })\n  const passwordHash = bcrypt.hashSync(password, 10)\n  const user = await prisma.user.create({ data: { email, passwordHash } })\n  return NextResponse.json({ id: user.id, email: user.email })\n}`;

  // CRUD routes for models
  for (const m of ir.models) {
    const base = m.name.toLowerCase() + "s";
    files[`/app/api/${base}/route.ts`] = `import { NextRequest, NextResponse } from 'next/server'\nimport { PrismaClient } from '@prisma/client'\nconst prisma = new PrismaClient()\nexport async function GET(){ const data = await prisma.${base}.findMany(); return NextResponse.json(data) }\nexport async function POST(req: NextRequest){ const body = await req.json(); const created = await prisma.${base}.create({ data: body }); return NextResponse.json(created,{ status: 201 }) }`;
  }

  return files;
}

// ---------------- Utilities ----------------
function buildProject(command: string): Project {
  const ir = parseCommand(command);
  const frontend = genFrontendFiles(ir);
  const backend = genNextApiFiles(ir);
  const prisma = backend["/prisma/schema.prisma"]; // same
  return { command, ir, frontend, backend, prisma };
}

function useHistory<T>(initial: T) {
  const [past, setPast] = useState<T[]>([]);
  const [present, setPresent] = useState<T>(initial);
  const [future, setFuture] = useState<T[]>([]);
  return {
    state: present,
    canUndo: past.length > 0,
    canRedo: future.length > 0,
    set: (next: T) => {
      setPast((p) => [...p, present]);
      setPresent(next);
      setFuture([]);
    },
    undo: () => {
      if (!past.length) return;
      const prev = past[past.length - 1];
      setPast((p) => p.slice(0, -1));
      setFuture((f) => [present, ...f]);
      setPresent(prev);
    },
    redo: () => {
      if (!future.length) return;
      const next = future[0];
      setFuture((f) => f.slice(1));
      setPast((p) => [...p, present]);
      setPresent(next);
    },
  };
}

function asSandpackFiles(frontend: Record<string, string>) {
  // Sandpack expects object without leading slash
  const files: Record<string, { code: string }> = {};
  Object.entries(frontend).forEach(([path, code]) => {
    files[path.replace(/^\//, "")] = { code };
  });
  return files;
}

function downloadZip(project: Project) {
  const zip = new JSZip();
  const frontend = zip.folder("frontend")!;
  const backend = zip.folder("backend-nextjs")!;
  Object.entries(project.frontend).forEach(([p, c]) => frontend.file(p.replace(/^\//, ""), c));
  Object.entries(project.backend).forEach(([p, c]) => backend.file(p.replace(/^\//, ""), c));
  zip.file("README.md", `# Loveable Generated Project\n\n## Frontend (preview)\n- React + Tailwind (CDN for preview)\n\n## Backend\n- Next.js App Router\n- Prisma + PostgreSQL\n- JWT Auth endpoints\n\n### Setup\n1. Copy backend-nextjs to a new repo, run \`npm i\`\n2. Set \`.env\` from \`.env.example\` (DATABASE_URL, JWT_SECRET)\n3. Run \`npx prisma migrate dev\`\n4. \`npm run dev\` or deploy to Vercel\n`);
  zip.generateAsync({ type: "blob" }).then((blob) => {
    const a = document.createElement("a");
    a.href = URL.createObjectURL(blob);
    a.download = "loveable-project.zip";
    a.click();
    URL.revokeObjectURL(a.href);
  });
}

